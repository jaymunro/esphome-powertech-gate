#!/usr/bin/env python3
"""Validate controller definitions and generate reproducible ESPHome packages."""
import argparse,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
FIELDS={'id','family','protocol','supports_pedestrian','pedestrian_stopped_status','full_open_min_position','closed_position','closed_position_tolerance','tested_firmware','validation','opening_event_mode_hint'}
def validate(p):
    if set(p)!=FIELDS: raise ValueError('Model fields must exactly match the documented schema')
    if not re.fullmatch(r'[A-Z0-9_-]{2,32}',p['id']): raise ValueError('Invalid model id')
    if p['family']!='WBT01' or p['protocol']!='legacy_uart_v1': raise ValueError('Unsupported transport/protocol; a new driver is required')
    if type(p['opening_event_mode_hint']) is not bool: raise ValueError('opening_event_mode_hint must be boolean')
    if type(p['supports_pedestrian']) is not bool: raise ValueError('supports_pedestrian must be boolean')
    if not re.fullmatch(r'(PED|SINGLE|FULL) STOPPED',p['pedestrian_stopped_status']): raise ValueError('Unsupported pedestrian status signature')
    lo,hi=p['closed_position'],p['full_open_min_position']
    if type(lo) is not int or type(hi) is not int or not 0<=lo<hi<=100: raise ValueError('Positions must be integers in 0..100, closed < full-open')
    tolerance=p['closed_position_tolerance']
    if type(tolerance) is not int or not 0<=tolerance<=5 or lo+tolerance>=hi: raise ValueError('Closed tolerance must be 0..5 and below full-open')
    if not isinstance(p['tested_firmware'],list) or not p['tested_firmware'] or not all(isinstance(x,str) for x in p['tested_firmware']): raise ValueError('Document tested firmware')
    if not isinstance(p['validation'],str) or not p['validation']: raise ValueError('Document validation and remaining limitations')
    return p

def render_profile(p):
    return ('# Generated by tools/generate.py; edit models/*.json instead.\nsubstitutions:\n'
      f'  profile_model: "{p["id"]}"\n'
      f'  profile_pedestrian_status: "{p["pedestrian_stopped_status"]}"\n'
      f'  profile_full_open_min: "{p["full_open_min_position"]}"\n'
      f'  profile_closed_position: "{p["closed_position"]}"\n'
      f'  profile_closed_tolerance: "{p["closed_position_tolerance"]}"\n'
      f'  profile_opening_event_mode_hint: "{str(p["opening_event_mode_hint"]).lower()}"\n'
      f'  profile_supports_pedestrian: "{str(p["supports_pedestrian"]).lower()}"\n')

def outputs():
    schema=json.loads((ROOT/'settings/ps19001.json').read_text())
    fields=schema['fields']
    if [f['field'] for f in fields]!=list('123456789ABCDEFGHIJ'): raise ValueError('Settings fields must be 1..J')
    settings_template=(ROOT/'templates/gate_settings.inc.in').read_text()
    specs=[];publish=[];selects=[]
    for i,f in enumerate(fields):
        specs.append("    {'%s', %d, %s, {%s}}," % (f['field'],f['offset'],str(f['format']=='decimal_width_2').lower(),', '.join(json.dumps(v) for v in f['options'])))
        ident='setting_'+f['field'].lower()
        publish.append(f'    id({ident}).publish_state(value({i}));')
        options=list(f['options'])
        if f['field'] in schema['hall_current']['fields']:
            options+= [v for v in schema['hall_current']['options'] if v not in options]
        selects.append(f'  - platform: template\n    id: {ident}\n    name: {json.dumps(f["name"])}\n    entity_category: config\n    lambda: return {{}};\n    update_interval: never\n    options:\n'+''.join('      - '+json.dumps(v)+'\n' for v in options)+f"    set_action:\n      - lambda: |-\n          if (id(gate_settings_change)) id(gate_settings_change)('{f['field']}', x);\n")
    hall=schema['hall_current']
    settings_source=settings_template.replace('@@SETTINGS_FIELDS@@','\n'.join(specs)).replace('@@SETTINGS_PUBLISH@@','\n'.join(publish)).replace('@@HALL_OPTIONS@@',', '.join(json.dumps(v) for v in hall['options'])).replace('@@HALL_OFFSET@@',str(hall['offset']))
    template=(ROOT/'templates/powertech-gate.yaml.in').read_text()
    template=template.replace('@@SETTINGS_TEXT_SENSORS@@','').replace('@@SETTINGS_SELECT@@','select:\n'+''.join(selects))
    body=(ROOT/'src/gate_feedback.inc').read_text()+'\n'+settings_source.rstrip()+'\n'+(ROOT/'src/gate_client_body.inc').read_text()
    if template.count('@@CONTROLLER_SOURCE@@')!=1: raise ValueError('Template marker missing/duplicated')
    result={ROOT/'packages/powertech-gate.yaml':'# Generated by tools/generate.py; do not edit this file directly.\n'+template.replace('@@CONTROLLER_SOURCE@@','\n'.join('          '+line for line in body.splitlines()))}
    result[ROOT/'src/gate_settings_generated.inc']=settings_source
    seen=set()
    for path in sorted((ROOT/'models').glob('*.json')):
        p=validate(json.loads(path.read_text()))
        if p['id'] in seen: raise ValueError('Duplicate model id')
        seen.add(p['id']);result[ROOT/'packages/models'/f'{path.stem}.yaml']=render_profile(p)
    if not seen: raise ValueError('At least one model is required')
    return result

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text()!=content: raise SystemExit(f'Generated file out of date: {path.relative_to(ROOT)}')
        else: path.write_text(content)
    print('Controller definitions and generated packages are consistent.')
if __name__=='__main__': main()
